"""Inter (SIL Open Font License) -> gen/font_ui.h: two proportional fonts with 4-level anti-aliasing.
Each glyph is H rows of 32 bits, 2 bits per pixel (leftmost pixel in the low bits), plus an advance width."""
from PIL import Image, ImageFont, ImageDraw
import numpy as np
DIR = '/usr/share/fonts/opentype/inter/'
FONTS = [("BODY", "Inter-Medium.otf", 10), ("TITLE", "Inter-SemiBold.otf", 11)]
out = ["/* generated by engine/font_gen.py from Inter (SIL Open Font License 1.1) */", "#include <stdint.h>"]
for name, file, px in FONTS:
    f = ImageFont.truetype(DIR + file, px)
    asc, desc = f.getmetrics()
    H = asc + desc
    rows, adv = [], []
    for ch in range(32, 127):
        w = max(1, round(f.getlength(chr(ch))))
        im = Image.new("L", (16, H), 0)
        ImageDraw.Draw(im).text((0, 0), chr(ch), font=f, fill=255)
        a = np.asarray(im).astype(int)
        lev = np.clip((a + 42) // 85, 0, 3)                      # 4 levels
        assert not lev[:, 15].any(), chr(ch)
        rows.append([int(sum(int(v) << (2 * x) for x, v in enumerate(r))) for r in lev])
        adv.append(min(w, 15))
    out.append(f"#define FONT_{name}_H {H}")
    out.append(f"static const uint8_t FONT_{name}_W[95] = {{{','.join(map(str, adv))}}};")
    out.append(f"static const uint32_t FONT_{name}[95][{H}] = {{")
    out += ["  {" + ",".join(hex(v) for v in r) + "}," for r in rows]
    out.append("};")
    print(name, "height", H, "ascent", asc, "average advance", sum(adv) / len(adv))
open('/home/user/kokosd/gen/font_ui.h', 'w').write("\n".join(out) + "\n")
