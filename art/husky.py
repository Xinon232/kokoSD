"""Koko's portrait for the title screen: an original drawing built from simple shapes, rendered large and
reduced to 96x88 pixels in 15 colours (+ transparent). Output: gen/husky.h (4 bits per pixel) and art/husky.png."""
import os as _os; ROOT = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))  # repository root
from PIL import Image, ImageDraw
import numpy as np
S = 8                                   # supersampling
W, H = 96, 88
BG = (0, 0, 0, 0)
GREY, DARK, WHITE, BLACK = (108, 122, 150), (64, 74, 98), (246, 248, 252), (22, 26, 38)
EAR, BLUE, BLUE2, TONGUE, TLINE, SHINE = (240, 186, 198), (110, 205, 250), (48, 128, 214), (240, 120, 142), (204, 84, 110), (92, 100, 124)
im = Image.new("RGBA", (W * S, H * S), BG)
d = ImageDraw.Draw(im)
def P(pts): return [(x * S, y * S) for x, y in pts]
def E(x0, y0, x1, y1, **k): d.ellipse([x0 * S, y0 * S, x1 * S, y1 * S], **k)
# ears: dark outer, pink inner
for sx in (1, -1):
    cx = 48
    d.polygon(P([(cx + sx * 10, 24), (cx + sx * 32, 1), (cx + sx * 41, 36)]), fill=DARK)
    d.polygon(P([(cx + sx * 18, 24), (cx + sx * 30, 9), (cx + sx * 35, 31)]), fill=EAR)
# head with fluffy cheeks
E(9, 13, 87, 81, fill=GREY)
for sx in (1, -1):
    cx = 48
    d.polygon(P([(cx + sx * 36, 46), (cx + sx * 47, 56), (cx + sx * 39, 60), (cx + sx * 45, 68), (cx + sx * 34, 72)]), fill=GREY)
# dark cap coming down between the eyes (the husky mask)
d.polygon(P([(20, 22), (34, 15), (48, 13), (62, 15), (76, 22), (62, 31), (48, 46), (34, 31)]), fill=DARK)
# white face: two eye patches, the muzzle and chin, a blaze up the nose
E(17, 29, 46, 59, fill=WHITE); E(50, 29, 79, 59, fill=WHITE)
E(24, 45, 72, 85, fill=WHITE)
d.polygon(P([(44, 36), (48, 27), (52, 36), (51, 52), (45, 52)]), fill=WHITE)
E(27, 23, 35, 29, fill=WHITE); E(61, 23, 69, 29, fill=WHITE)                       # eyebrow dots
# big eyes: black rim, blue iris, pupil, highlight
for ex in (32, 64):
    E(ex - 8, 36, ex + 8, 53, fill=BLACK)
    E(ex - 6.5, 37.5, ex + 6.5, 51.5, fill=BLUE)
    E(ex - 6.5, 44, ex + 6.5, 51.5, fill=BLUE2); E(ex - 6.5, 40, ex + 6.5, 47, fill=BLUE)
    E(ex - 3.5, 40.5, ex + 3.5, 48.5, fill=BLACK)
    E(ex - 5.5, 38.5, ex - 1.5, 42.5, fill=WHITE); E(ex + 1.5, 46, ex + 3.5, 48, fill=WHITE)
# tongue under the mouth line, then nose and smile on top
E(43, 70, 53, 85, fill=TONGUE); d.line(P([(48, 75), (48, 82)]), fill=TLINE, width=int(1.2 * S))
d.rectangle([40 * S, 66 * S, 56 * S, 71.5 * S], fill=WHITE)
E(41, 55, 55, 65, fill=BLACK); E(44, 56.5, 49, 59, fill=SHINE)
d.line(P([(48, 64), (48, 70)]), fill=BLACK, width=int(1.6 * S))
d.arc([37 * S, 61 * S, 48 * S, 75 * S], 15, 150, fill=BLACK, width=int(1.7 * S)); d.arc([48 * S, 61 * S, 59 * S, 75 * S], 30, 165, fill=BLACK, width=int(1.7 * S))
small = im.resize((W, H), Image.LANCZOS)
a = np.asarray(small).astype(int)
alpha = a[..., 3] >= 128
mix = lambda p, q: tuple((x + y) // 2 for x, y in zip(p, q))
pal = np.array([GREY, DARK, WHITE, BLACK, EAR, BLUE, BLUE2, TONGUE, TLINE, SHINE, mix(GREY, WHITE), mix(DARK, GREY), mix(BLACK, WHITE), mix(BLUE, BLACK), mix(WHITE, mix(BLACK, WHITE))])
dist = ((a[..., None, :3] - pal[None, None]) ** 2).sum(-1)          # fixed palette: nearest colour, so the blue and pink survive
idx = dist.argmin(-1) + 1
idx[~alpha] = 0                                                   # 0 = transparent
out = Image.new("RGB", (W, H), (58, 90, 165))
px = out.load()
for y in range(H):
    for x in range(W):
        if idx[y, x]: px[x, y] = tuple(int(v) for v in pal[idx[y, x] - 1])
out.resize((W * 5, H * 5), Image.NEAREST).save(ROOT + '/art/husky.png')
rows = []
for y in range(H):
    bs = [(int(idx[y, x]) | (int(idx[y, x + 1]) << 4)) for x in range(0, W, 2)]
    rows.append(",".join(map(str, bs)))
c15 = [((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)) for r, g, b in pal]
open(ROOT + '/gen/husky.h', 'w').write(
    "/* generated by art/husky.py: Koko's portrait, 4 bits per pixel, 0 = transparent */\n#include <stdint.h>\n"
    f"#define HUSKY_W {W}\n#define HUSKY_H {H}\n"
    "static const uint16_t HUSKY_PAL[15] = {" + ",".join(map(str, c15)) + "};\n"
    f"static const uint8_t HUSKY[{H}][{W // 2}] = {{\n" + ",\n".join("{" + r + "}" for r in rows) + "\n};\n")
print("ok", W, H)
